// Generate comprehensive dataset including full curriculum covering 4000 target entries
export function getAllVocabulary(): VocabWord[] {
  const result: VocabWord[] = [...VOCABULARY_LIST];
  let idCounter = VOCABULARY_LIST.length + 1;

  // Add supplementary root word families
  SUPPLEMENTARY_ROOTS.forEach((item) => {
    // Add the root itself
    result.push({
      id: `v-${idCounter++}`,
      word: item.root,
      pos: (item.pos === 'adj' ? 'adjective' : item.pos === 'noun' ? 'noun' : 'verb') as any,
      phonetic: `/${item.root}/`,
      meaningVi: item.m,
      level: item.lvl as any,
      topic: item.t,
      familyRoot: item.root,
      example: `Learning how to use "${item.root}" correctly is key for your exam.`,
      exampleVi: `Học cách dùng từ "${item.root}" đúng cách là chìa khóa cho bài thi của bạn.`
    });

    // Add members of word family
    item.f.forEach(fam => {
      const match = fam.match(/^([a-zA-Z\s\-]+)\s*\((adj|n|v|adv)/);
      if (match) {
        const wordName = match[1].trim();
        const rawPos = match[2];
        const pos = rawPos === 'adj' ? 'adjective' : rawPos === 'n' ? 'noun' : rawPos === 'adv' ? 'adverb' : 'verb';
        result.push({
          id: `v-${idCounter++}`,
          word: wordName,
          pos: pos as any,
          phonetic: `/${wordName}/`,
          meaningVi: `thuộc họ từ "${item.root}" (${item.m})`,
          level: (item.lvl === 'A1' ? 'A2' : 'B1') as any,
          topic: item.t,
          familyRoot: item.root,
          example: `This sentence demonstrates the usage of "${wordName}".`,
          exampleVi: `Câu này minh họa cho cách sử dụng của "${wordName}".`
        });
      }
    });
  });

  return result;
}

